/**
 * コラムの題材の候補（まだ「すぐには書かない」検索意図の一覧）。
 *
 * サービスごとに、検索する人が持つ疑問を洗い出したもの。自動投稿は、ここからは選ばない。
 * 書けるようになった候補を、topics.ts に「題材」として上げる（書く内容・使う事実シートの節を決める）。
 *
 * 題材に上げる条件
 *   - needs が空 … 事実シートと一般的な知識で書ける。書く内容（angle）を決めれば、題材にできる
 *   - needs がある … そこに書いたもの（公式情報の確認・会社への確認・当社の施工写真）がそろってから
 *     数値や制度が要る候補は、先に docs/VERIFIED_FACTS.md に出典つきで事実を足す
 *
 * 決まり
 *   - 1候補 ＝ 1検索意図 ＝ 1主キーワード。固定ページ・公開済みの記事・題材・ほかの候補と同じ検索語にしない
 *     （npm run seo:audit が重なりを知らせる）
 *   - 固定ページ（サービス・地域）と同じ検索意図のものは、候補にしない。そのページを直す
 *   - 同じ内容の言い換えで数を増やさない。記事にしたときに、既存の記事と本文が重なるものは入れない
 *
 * 優先度（docs/SEO_ROADMAP.md）
 *   P0 … 問い合わせに近い疑問・当社の施工事例にもとづいて書ける疑問
 *   P1 … 検索する人の多い、一般的な疑問
 *   P2 … 細かい疑問・事実の確認に手間がかかるもの
 */
