/** 写真の代替テキスト・署名に使う表記（例：代表取締役 加太 駆）。代表者が未設定なら空文字 */
export function representativeLabel(): string {
  const c = siteConfig.company;
  if (!c.representative) return "";
  return c.representativeTitle ? `${c.representativeTitle} ${c.representative}` : c.representative;
}
