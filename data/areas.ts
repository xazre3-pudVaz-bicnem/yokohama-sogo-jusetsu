/**
 * 対応エリア（地域ページ）
 *
 * 地域ページは「地域名だけを差し替えた同じ文章」にしない。1ページごとに、その地域にしか当てはまらない内容
 * （地形・住宅の成り立ち・駅・町名・自治体の制度）を、公式の出典つきで持たせる。
 * 書いてよい事実は、区・市・国の公式ページで確かめたものだけ（sources に URL、checkedAt に確認日）。
 * 人口などの統計は「いつ時点の、どの統計か」を必ず添える。
 *
 * 地域を増やすとき（泉区・栄区・港南区・旭区・保土ケ谷区・瀬谷区など）
 *   1. その区の公式ページで、地形・住宅地の成り立ち・駅・町名を確かめる
 *   2. 下の配列に1件足す（published: true にするとページ・メニュー・サイトマップに出る）
 *   3. その地域の施工事例があれば、data/works.ts の area.areaSlug に同じ slug を入れる
 *   4. 固有の内容が3区画以上そろわないうちは published: false のままにする（薄いページを増やさない）
 */

export type AreaFact = { label: string; value: string; note?: string };

export type Area = {
  slug: string;
  /** 正式な地域名（例：横浜市戸塚区） */
  name: string;
  /** 短い呼び方（例：戸塚区） */
  shortName: string;
  kind: "ward" | "city";
  published: boolean;
  /** 取りにいく検索語は data/seo-keyword-map.ts に書く */
  seo: { title: string; description: string };
  h1: string;
  lead: string;
  image: ImageKey;
  imageAlt: string;
  /** 基礎データ（出典つき） */
  facts: AreaFact[];
  /** この地域にしか当てはまらない内容 */
  sections: { id: string; heading: string; body: string[]; items?: { title: string; body: string }[] }[];
  /** サービス × 地域（この地域でその工事を頼むときの話。サービスページの内容と重ねない） */
  serviceNotes: { service: string; title: string; body: string }[];
  /** 町名（公式の町名一覧より） */
  towns?: string[];
  stations?: { name: string; lines: string }[];
  /** 隣り合う区・市 */
  neighbors?: string[];
  faqs: { q: string; a: string }[];
  sources: { label: string; url: string }[];
  /** 出典のページで事実を確かめた日 */
  checkedAt: string;
  /** ページの内容を最後に直した日（YYYY-MM-DD）。sitemap.xml の lastmod に使う */
  updatedAt: string;
};

